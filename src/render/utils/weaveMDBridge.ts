import type { WeaveMDApi } from '@main/preload';
import type {
  AccountInfo,
  IFile,
  IHistoryEntry,
  ISettings,
  IUser,
  IUserPublic,
  LanguageType,
  ThemeType,
} from '@shared/types';
import { validatePassword, validateUsername } from './validators';

type ApiResult<T = unknown> = {
  success: boolean;
  data?: T;
  error?: string;
  message?: string;
};

type UsernameCheckResult = {
  available: boolean;
  message: string;
};

type BrowserMockState = {
  users: IUser[];
  files: IFile[];
  historyEntries: IHistoryEntry[];
  settings: ISettings[];
  sessions: Array<{
    token: string;
    userId: string;
    createdAt: string;
  }>;
  importedFileSeed: number;
  isMaximized: boolean;
};

const MOCK_STORAGE_KEY = 'weavemd_browser_mock_v1';
const DEFAULT_THEME: ThemeType = 'light-header';
const DEFAULT_LANGUAGE: LanguageType = 'zh-CN';
const BRIDGE_UNAVAILABLE_MESSAGE =
  'Electron bridge is unavailable in browser preview mode. Using interactive local mock.';
const DEFAULT_WELCOME_FILE_NAME = 'welcome.md';
const DEFAULT_WELCOME_CONTENT = `# Welcome to WeaveMD

This browser preview runs on a local mock bridge instead of Electron.

## What works here

- Register and log in with local mock accounts
- Create, open, edit, save, and delete files
- Browse file history from the History panel
- Persist theme and language settings per account

## Try this

1. Create a new file from the top bar
2. Edit content in Monaco
3. Wait for auto-save or trigger save by switching files
4. Open History to jump between saved files
`;
const IMPORT_FALLBACK_TEMPLATE = `# Imported Preview File

This file was generated by the browser mock bridge because the local file picker
is unavailable in the current preview environment.

- You can still edit and save it into mock history.
- Real Electron IPC will replace this behavior in the desktop app.
`;

const EXPORT_MIME: Record<string, string> = {
  md: 'text/markdown;charset=utf-8',
  html: 'text/html;charset=utf-8',
  doc: 'application/msword',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  pdf: 'application/pdf',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
};

const createEmptyState = (): BrowserMockState => ({
  users: [],
  files: [],
  historyEntries: [],
  settings: [],
  sessions: [],
  importedFileSeed: 1,
  isMaximized: false,
});

const nowIso = () => new Date().toISOString();

const createId = (prefix: string) => {
  const randomPart =
    typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function'
      ? crypto.randomUUID()
      : `${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 10)}`;

  return `${prefix}_${randomPart}`;
};

const toPublicUser = (user: IUser): IUserPublic => ({
  id: user.id,
  username: user.username,
  createdAt: user.createdAt,
  lastLogin: user.lastLogin,
});

const createSettingsRecord = (userId: string): ISettings => ({
  id: createId('settings'),
  userId,
  theme: DEFAULT_THEME,
  language: DEFAULT_LANGUAGE,
  customColors: null,
});

const createHistoryEntry = (fileId: string, version: number, content: string): IHistoryEntry => ({
  id: createId('history'),
  fileId,
  version,
  diff: content,
  savedAt: nowIso(),
});

const normalizeUsername = (username: string) => username.trim().toLowerCase();

const loadState = (): BrowserMockState => {
  if (typeof window === 'undefined') {
    return createEmptyState();
  }

  try {
    const raw = window.localStorage.getItem(MOCK_STORAGE_KEY);
    if (!raw) {
      return createEmptyState();
    }

    const parsed = JSON.parse(raw) as Partial<BrowserMockState>;
    return {
      users: Array.isArray(parsed.users) ? parsed.users : [],
      files: Array.isArray(parsed.files) ? parsed.files : [],
      historyEntries: Array.isArray(parsed.historyEntries) ? parsed.historyEntries : [],
      settings: Array.isArray(parsed.settings) ? parsed.settings : [],
      sessions: Array.isArray(parsed.sessions) ? parsed.sessions : [],
      importedFileSeed: typeof parsed.importedFileSeed === 'number' ? parsed.importedFileSeed : 1,
      isMaximized: Boolean(parsed.isMaximized),
    };
  } catch {
    return createEmptyState();
  }
};

const saveState = (state: BrowserMockState) => {
  if (typeof window === 'undefined') {
    return;
  }

  window.localStorage.setItem(MOCK_STORAGE_KEY, JSON.stringify(state));
};

const mutateState = <T>(updater: (state: BrowserMockState) => T): T => {
  const state = loadState();
  const result = updater(state);
  saveState(state);
  return result;
};

const ensureSettings = (state: BrowserMockState, userId: string): ISettings => {
  let record = state.settings.find((item) => item.userId === userId);
  if (!record) {
    record = createSettingsRecord(userId);
    state.settings.push(record);
  }
  return record;
};

const ensureWelcomeFile = (state: BrowserMockState, userId: string) => {
  const hasAnyFile = state.files.some((file) => file.userId === userId && !file.deletedAt);
  if (hasAnyFile) {
    return;
  }

  const createdAt = nowIso();
  const file: IFile = {
    id: createId('file'),
    userId,
    name: DEFAULT_WELCOME_FILE_NAME,
    content: DEFAULT_WELCOME_CONTENT,
    createdAt,
    modifiedAt: createdAt,
    deletedAt: null,
  };

  state.files.push(file);
  state.historyEntries.push(createHistoryEntry(file.id, 1, file.content));
};

const getVisibleFiles = (state: BrowserMockState, userId: string) =>
  state.files
    .filter((file) => file.userId === userId && !file.deletedAt)
    .sort((a, b) => b.modifiedAt.localeCompare(a.modifiedAt));

const getNextHistoryVersion = (state: BrowserMockState, fileId: string) =>
  state.historyEntries
    .filter((entry) => entry.fileId === fileId)
    .reduce((maxVersion, entry) => Math.max(maxVersion, entry.version), 0) + 1;

const createSuccessResult = <T>(data: T, message?: string): ApiResult<T> => ({
  success: true,
  data,
  message,
});

const createFailureResult = <T = unknown>(message: string): ApiResult<T> => ({
  success: false,
  error: message,
  message,
});

const triggerBrowserDownload = (content: string, filename: string, mimeType: string) => {
  if (typeof document === 'undefined' || typeof URL === 'undefined') {
    return false;
  }

  const blob = new Blob([content], { type: mimeType });
  const objectUrl = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = objectUrl;
  link.download = filename;
  link.style.display = 'none';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(objectUrl);
  return true;
};

const readBrowserSelectedFile = (): Promise<
  ApiResult<{ path: string; name: string; content: string }>
> => {
  if (typeof document === 'undefined') {
    const name = `imported-preview-${Date.now().toString(36)}.md`;
    return Promise.resolve(
      createSuccessResult({
        path: name,
        name,
        content: IMPORT_FALLBACK_TEMPLATE,
      })
    );
  }

  return new Promise((resolve) => {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = '.md,.markdown,.txt,text/markdown,text/plain';

    input.addEventListener('change', async () => {
      const selectedFile = input.files?.[0];
      if (!selectedFile) {
        resolve(createFailureResult('File selection cancelled.'));
        return;
      }

      try {
        const content = await selectedFile.text();
        resolve(
          createSuccessResult({
            path: selectedFile.name,
            name: selectedFile.name,
            content,
          })
        );
      } catch {
        resolve(createFailureResult('Failed to read the selected file.'));
      }
    });

    input.click();
  });
};

export const createNoopWeaveMDApi = (): WeaveMDApi => ({
  auth: {
    login: async (username, password) =>
      mutateState((state) => {
        const normalizedUsername = normalizeUsername(username);
        const user = state.users.find(
          (candidate) =>
            normalizeUsername(candidate.username) === normalizedUsername &&
            candidate.passwordHash === password
        );

        if (!user) {
          return createFailureResult('Invalid username or password.');
        }

        user.lastLogin = nowIso();
        ensureSettings(state, user.id);
        ensureWelcomeFile(state, user.id);

        const token = createId('mock-token');
        state.sessions = [
          { token, userId: user.id, createdAt: nowIso() },
          ...state.sessions.filter((session) => session.userId !== user.id),
        ].slice(0, 20);

        return createSuccessResult(
          {
            token,
            user: toPublicUser(user),
          },
          'Logged in with browser mock bridge.'
        );
      }),
    register: async (username, password) =>
      mutateState((state) => {
        const normalizedUsername = username.trim();
        const usernameValidation = validateUsername(normalizedUsername);
        if (!usernameValidation.valid) {
          return createFailureResult(usernameValidation.message);
        }

        const passwordValidation = validatePassword(password);
        if (!passwordValidation.valid) {
          return createFailureResult(passwordValidation.message);
        }

        const exists = state.users.some(
          (user) => normalizeUsername(user.username) === normalizeUsername(normalizedUsername)
        );
        if (exists) {
          return createFailureResult('Username is already taken.');
        }

        const createdAt = nowIso();
        const user: IUser = {
          id: createId('user'),
          username: normalizedUsername,
          passwordHash: password,
          createdAt,
          updatedAt: createdAt,
          lastLogin: null,
        };

        state.users.push(user);
        state.settings.push(createSettingsRecord(user.id));
        ensureWelcomeFile(state, user.id);

        return createSuccessResult(undefined, 'Account created in browser mock bridge.');
      }),
    checkUsername: async (username) => {
      const normalizedUsername = username.trim();
      const usernameValidation = validateUsername(normalizedUsername);
      if (!usernameValidation.valid) {
        return {
          available: false,
          message: usernameValidation.message,
        } satisfies UsernameCheckResult;
      }

      const state = loadState();
      const exists = state.users.some(
        (user) => normalizeUsername(user.username) === normalizeUsername(normalizedUsername)
      );

      return {
        available: !exists,
        message: exists ? 'Username is already taken.' : 'Username is available.',
      } satisfies UsernameCheckResult;
    },
    validateToken: async (token) => {
      const state = loadState();
      const session = state.sessions.find((candidate) => candidate.token === token);
      if (!session) {
        return createFailureResult('Token is invalid or expired.');
      }

      const user = state.users.find((candidate) => candidate.id === session.userId);
      if (!user) {
        return createFailureResult('Token user was not found.');
      }

      ensureWelcomeFile(state, user.id);
      ensureSettings(state, user.id);
      saveState(state);

      return createSuccessResult(toPublicUser(user));
    },
  },
  file: {
    create: async (userId, name) =>
      mutateState((state) => {
        const user = state.users.find((candidate) => candidate.id === userId);
        if (!user) {
          return createFailureResult('User not found.');
        }

        const createdAt = nowIso();
        const safeName = name.trim() || `untitled-${Date.now().toString(36)}.md`;
        const file: IFile = {
          id: createId('file'),
          userId,
          name: safeName,
          content: '',
          createdAt,
          modifiedAt: createdAt,
          deletedAt: null,
        };

        state.files.push(file);
        state.historyEntries.push(createHistoryEntry(file.id, 1, file.content));

        return createSuccessResult(file, 'File created in browser mock bridge.');
      }),
    open: async () => readBrowserSelectedFile(),
    save: async (fileId, content, userId) =>
      mutateState((state) => {
        const file = state.files.find(
          (candidate) =>
            candidate.id === fileId && candidate.userId === userId && candidate.deletedAt === null
        );

        if (!file) {
          return createFailureResult('File not found.');
        }

        file.content = content;
        file.modifiedAt = nowIso();

        state.historyEntries.push(
          createHistoryEntry(file.id, getNextHistoryVersion(state, file.id), content)
        );

        return createSuccessResult(file, 'File saved in browser mock bridge.');
      }),
    delete: async (fileId, userId) =>
      mutateState((state) => {
        const file = state.files.find(
          (candidate) =>
            candidate.id === fileId && candidate.userId === userId && candidate.deletedAt === null
        );

        if (!file) {
          return createFailureResult('File not found.');
        }

        file.deletedAt = nowIso();
        return createSuccessResult(undefined, 'File deleted from browser mock bridge.');
      }),
    list: async (userId) => {
      const state = loadState();
      return createSuccessResult(getVisibleFiles(state, userId));
    },
    get: async (fileId, userId) => {
      const state = loadState();
      const file = state.files.find(
        (candidate) =>
          candidate.id === fileId && candidate.userId === userId && candidate.deletedAt === null
      );

      if (!file) {
        return createFailureResult('File not found.');
      }

      return createSuccessResult(file);
    },
    write: async (_filePath, _content) =>
      createSuccessResult(undefined, 'Browser bridge: write not available'),
    deleteDisk: async (_filePath) =>
      createSuccessResult(undefined, 'Browser bridge: deleteDisk not available'),
    readDisk: async (_filePath) =>
      createSuccessResult(undefined, 'Browser bridge: readDisk not available'),
  },
  history: {
    list: async (fileId) => {
      const state = loadState();
      const entries = state.historyEntries
        .filter((entry) => entry.fileId === fileId)
        .sort((a, b) => b.version - a.version);
      return createSuccessResult(entries);
    },
    get: async (fileId, userId) => {
      const state = loadState();
      const file = state.files.find(
        (candidate) =>
          candidate.id === fileId && candidate.userId === userId && candidate.deletedAt === null
      );

      if (!file) {
        return createFailureResult('History file not found.');
      }

      const entries = state.historyEntries
        .filter((entry) => entry.fileId === fileId)
        .sort((a, b) => b.version - a.version);

      return createSuccessResult({
        file,
        entries,
      });
    },
  },
  settings: {
    get: async (userId) => {
      const state = loadState();
      const settings = ensureSettings(state, userId);
      saveState(state);
      return createSuccessResult(settings);
    },
    update: async (userId, settingsUpdate) =>
      mutateState((state) => {
        const settings = ensureSettings(state, userId);

        if (typeof settingsUpdate.theme === 'string') {
          settings.theme = settingsUpdate.theme as ThemeType;
        }
        if (typeof settingsUpdate.language === 'string') {
          settings.language = settingsUpdate.language as LanguageType;
        }
        if (
          typeof settingsUpdate.customColors === 'string' ||
          settingsUpdate.customColors === null
        ) {
          settings.customColors = settingsUpdate.customColors as string | null;
        }

        return createSuccessResult(settings, 'Settings saved in browser mock bridge.');
      }),
  },
  export: {
    file: async (req) => {
      const safeName = req.filename.endsWith(`.${req.format}`)
        ? req.filename
        : `${req.filename}.${req.format}`;
      const mime = EXPORT_MIME[req.format] ?? 'application/octet-stream';
      const body =
        req.format === 'html' || req.format === 'doc'
          ? `<!DOCTYPE html><html><head><meta charset="utf-8"><title>${req.filename}</title></head><body>${req.html}</body></html>`
          : req.content;
      const downloaded = triggerBrowserDownload(body, safeName, mime);
      return downloaded
        ? createSuccessResult({ filePath: safeName }, `Exported ${safeName} from browser mock bridge.`)
        : createFailureResult('Browser download is unavailable.');
    },
  },
  window: {
    minimize: async () => undefined,
    maximize: async () => {
      mutateState((state) => {
        state.isMaximized = true;
      });
    },
    unmaximize: async () => {
      mutateState((state) => {
        state.isMaximized = false;
      });
    },
    close: async () => undefined,
    isMaximized: async () => loadState().isMaximized,
  },
  dialog: {
    openFile: async () => readBrowserSelectedFile(),
    openFolder: async () =>
      createFailureResult('Folder selection is not available in browser mode.'),
    saveFile: async ({ defaultName }) =>
      createSuccessResult(
        {
          path: defaultName,
        },
        'Browser mock bridge uses automatic downloads instead of a native save dialog.'
      ),
    saveFilePath: async (_title, defaultName) =>
      createSuccessResult(
        {
          path: defaultName || 'untitled',
        },
        'Browser bridge save file path mock.'
      ),
    pickImage: async () => null,
  },
  account: {
    info: async (userId) => {
      const state = loadState();
      const user = state.users.find((candidate) => candidate.id === userId);
      if (!user) {
        return createFailureResult('Account not found.');
      }

      const activeFiles = getVisibleFiles(state, userId);
      const info: AccountInfo = {
        username: user.username,
        createdAt: user.createdAt,
        lastLogin: user.lastLogin,
        fileCount: activeFiles.length,
      };

      return createSuccessResult(info);
    },
    delete: async (userId) =>
      mutateState((state) => {
        const userIndex = state.users.findIndex((candidate) => candidate.id === userId);
        if (userIndex === -1) {
          return createFailureResult('Account not found.');
        }

        state.users.splice(userIndex, 1);
        state.settings = state.settings.filter((item) => item.userId !== userId);

        const deletedFileIds = state.files
          .filter((file) => file.userId === userId)
          .map((file) => file.id);
        state.files = state.files.filter((file) => file.userId !== userId);
        state.historyEntries = state.historyEntries.filter(
          (entry) => !deletedFileIds.includes(entry.fileId)
        );
        state.sessions = state.sessions.filter((session) => session.userId !== userId);

        return createSuccessResult(undefined, 'Account deleted from browser mock bridge.');
      }),
  },
  link: {
    openExternal: async () => {},
  },
  folder: {
    readFolder: async () => createSuccessResult([]),
    createFolder: async () =>
      createFailureResult('Folder creation is not available in browser mode.'),
    deleteFolder: async () =>
      createFailureResult('Folder deletion is not available in browser mode.'),
  },
  ai: {
    getConfig: async () => ({ success: false }),
    setConfig: async () => ({ success: false }),
    getConsent: async () => ({ success: false }),
    setConsent: async () => ({ success: false }),
    health: async () => ({ success: false }),
    chat: async () => ({ success: false }),
    chatAbort: async () => ({ success: true }),
    listConversations: async () => createSuccessResult([]),
    getConversation: async () => ({ success: false }),
    createConversation: async () => ({ success: false }),
    deleteConversation: async () => ({ success: false }),
    updateConversationSummary: async () => ({ success: false }),
    runAgent: async () => ({ success: false }),
    agentAbort: async () => ({ success: true }),
    rewritePreview: async () => ({ success: false }),
    listSkills: async () =>
      createSuccessResult([
        { name: 'polish_rewrite', description: '润色、缩写或扩写文本' },
        { name: 'tech_organize', description: '整理技术资料' },
        { name: 'kb_qa_guide', description: '基于知识库引导式问答' },
      ]),
    onStream: () => () => {},
  },
  kb: {
    list: async () => ({ success: false }),
    importFile: async () => ({ success: false }),
    importDir: async () => ({ success: false }),
    reindex: async () => ({ success: false }),
    delete: async () => ({ success: false }),
    status: async () => ({ success: false }),
    getSettings: async () => ({ success: false }),
    setSettings: async () => ({ success: false }),
  },
});

let hasWarnedAboutFallback = false;

export const ensureWeaveMDApi = (): WeaveMDApi => {
  if (typeof window === 'undefined') {
    return createNoopWeaveMDApi();
  }

  if (window.weaveMD) {
    return window.weaveMD;
  }

  const fallbackApi = createNoopWeaveMDApi();
  window.weaveMD = fallbackApi;

  if (!hasWarnedAboutFallback) {
    console.warn(BRIDGE_UNAVAILABLE_MESSAGE);
    hasWarnedAboutFallback = true;
  }

  return fallbackApi;
};
